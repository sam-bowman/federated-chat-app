// The browser-hardening headers the client's nginx sends (#281), and the Content-Security-Policy in particular, which has to fit how the client
// really works: index.html has INLINE scripts (the appearance one, which must run before the first paint, and the one that reloads the page
// when a build's files vanish during an upgrade), so `script-src 'self'` alone would stop both. They are allowed by their hash, taken from the
// index.html that was built, so a changed script gets a new hash by itself and the policy can never name a script that is not there.
//
//   node scripts/security-headers.mjs dist/index.html > security-headers.conf
//
// The Dockerfile runs this in the build stage and nginx.conf includes the result (see there for why it is repeated in every location).
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

/**
 * The text of every `<script>` in the page that has no `src`: the ones the browser would run from the page itself.
 *
 * Line endings are made LF first, because that is what the browser does to the page before it hashes or runs an inline script (the
 * HTML standard's input preprocessing turns CR LF and a lone CR into LF). A page built from files checked out with Windows line endings
 * has CR LF in its scripts, and a hash of THAT text never matches: the browser refuses the script (found by running the whole end-to-end
 * suite against the built image on Windows; a Linux checkout never shows it).
 */
export function inlineScripts(html) {
  const scripts = [];
  for (const match of html.replace(/\r\n?/g, "\n").matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (!/\bsrc\s*=/i.test(match[1])) scripts.push(match[2]);
  }
  return scripts;
}

/** `'sha256-...'`, the form a CSP source list takes. The hash is of the exact text between the tags, whitespace included. */
export function scriptHash(body) {
  return `'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`;
}

/**
 * The policy. What each part is for:
 * - script: this origin and the page's own inline scripts by hash. No `unsafe-inline`, no `unsafe-eval`: this is the part that stops a
 *   script a stranger's text managed to inject from running.
 * - style: React writes inline `style` attributes (colours reach CSS as custom properties), which only `unsafe-inline` allows.
 * - connect: in picker mode the client talks to ANY home server the person types, and to the voice server that server names, over
 *   https/wss (http/ws for a server on a local network), so this cannot name them. It limits nothing a script could not already do, which
 *   is why the script rule above matters more.
 * - img / media: pictures and uploads come from the home server, and for people on other servers from THEIR servers.
 * - frame-ancestors / form-action / base-uri / object: nothing embeds the client, nothing posts a form elsewhere, no plug-ins.
 */
export function buildPolicy(html) {
  const hashes = inlineScripts(html).map(scriptHash);
  return [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(" ")}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https: http:",
    "media-src 'self' blob: https: http:",
    "font-src 'self'",
    "connect-src 'self' https: http: wss: ws:",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

/** The other headers, with the values the client needs (the microphone for voice calls, nothing else). */
export const OTHER_HEADERS = {
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "microphone=(self), camera=(), geolocation=(), display-capture=(), payment=(), usb=(), serial=(), bluetooth=()",
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Resource-Policy": "same-origin",
};

/** nginx directives for all of them. `always`, so they are on an error page and a 304 as well. */
export function headersConf(html) {
  const headers = { "Content-Security-Policy": buildPolicy(html), ...OTHER_HEADERS };
  return (
    "# Generated by scripts/security-headers.mjs from the built index.html. Do not edit.\n" +
    Object.entries(headers)
      .map(([name, value]) => `add_header ${name} "${value}" always;`)
      .join("\n") +
    "\n"
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = process.argv[2];
  if (!file) throw new Error("usage: security-headers.mjs <path to the built index.html>");
  process.stdout.write(headersConf(readFileSync(file, "utf8")));
}
